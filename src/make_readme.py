"""Fill the Results block of README.md from results/*.json. No number in it is typed by hand.

Usage:
    python -m src.make_readme

README.md keeps its own text; only the part between the two marker lines below is replaced.
"""

import json
from pathlib import Path

from src.eval_run import load_questions

START = "<!-- RESULTS:START -->"
END = "<!-- RESULTS:END -->"
RESULTS_DIR = Path("results")
README = Path("README.md")

FAILURE_CASE = "q01"
RETRIEVAL_RUNS = [("dense", "e3_dense"), ("BM25", "e3_bm25"), ("hybrid (RRF, k=60)", "e3_hybrid")]
GENERATION_RUNS = [
    ("run 1 (first parser)", "generation_per_page_dense"),
    ("run 2 (stricter parser)", "generation_per_page_dense_v2"),
]


def _load(name: str) -> dict:
    return json.loads((RESULTS_DIR / f"{name}.json").read_text(encoding="utf-8"))


def retrieval_tables() -> str:
    """The E1 to E3 tables, copied from results/summary.md (which a script also generated)."""
    text = (RESULTS_DIR / "summary.md").read_text(encoding="utf-8")
    body = text[text.index("## E1") : text.index("## Best config so far")]
    return body.replace("\n## ", "\n### ").replace("## E1", "### E1", 1).strip()


def generation_table() -> str:
    rows = ["| run | citation check passed | false abstentions | abstained on unanswerable | failures |", "|---|---|---|---|---|"]
    for label, name in GENERATION_RUNS:
        r = _load(name)
        answered = [q for q in r["per_question"] if q["answerable"] and not q["abstained"]]
        passed = sum(q["ok"] for q in answered)
        unanswerable = [q for q in r["per_question"] if not q["answerable"]]
        abstained = sum(q["abstained"] for q in unanswerable)
        failures = ", ".join(f"{k} x{v}" for k, v in r["failure_counts"].items()) or "none"
        false_abs = ", ".join(r["false_abstentions"]) or "none"
        rows.append(f"| {label} | {passed} of {len(answered)} | {false_abs} | {abstained} of {len(unanswerable)} | {failures} |")
    return "\n".join(rows)


def failure_case_table() -> str:
    question = next(q for q in load_questions() if q["id"] == FAILURE_CASE)
    gold = {g["page"] for g in question["gold"]}
    rows = [
        f"Question {FAILURE_CASE}: *{question['question']}*  Gold page(s): {sorted(gold)}",
        "",
        "| search | rank of the gold page (top 10 checked) | pages returned, best first (top 5) |",
        "|---|---|---|",
    ]
    for label, name in RETRIEVAL_RUNS:
        row = next(q for q in _load(name)["per_question"] if q["id"] == FAILURE_CASE)
        pages = [c["pages"] for c in row["retrieved"]]
        rank = next((i + 1 for i, p in enumerate(pages) if gold & set(p)), None)
        shown = ", ".join(str(p[0]) if len(p) == 1 else str(p) for p in pages[:5])
        rows.append(f"| {label} | {rank if rank else 'not in top 10'} | {shown} |")
    return "\n".join(rows)


def build_block() -> str:
    return "\n\n".join([
        f"{START}\n*This block is generated by `python -m src.make_readme` from `results/*.json`. Do not edit it by hand.*",
        "#### Retrieval experiments (answerable questions only)",
        retrieval_tables(),
        "#### Generation and citation check (all 20 questions)",
        generation_table(),
        f"#### The failure case: {FAILURE_CASE}",
        failure_case_table(),
        END,
    ])


def replace_block(readme_text: str, block: str) -> str:
    """Replace everything from the START marker to the END marker (inclusive) with `block`."""
    start = readme_text.index(START)
    end = readme_text.index(END) + len(END)
    return readme_text[:start] + block + readme_text[end:]


def main() -> None:
    README.write_text(replace_block(README.read_text(encoding="utf-8"), build_block()), encoding="utf-8")
    print(f"updated the results block in {README}")


if __name__ == "__main__":
    main()
