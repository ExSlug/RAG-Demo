"""Build results/summary.md from the results/*.json files. Nothing in it is typed by hand.

Usage:
    python -m src.make_summary

Each experiment changes one thing and keeps the rest fixed (the project spec, section 11).
The best configuration in an experiment has the highest MRR; ties go to recall@3.
"""

import json
from pathlib import Path

RESULTS_DIR = Path("results")
NEAR_TIE = 0.05  # with 18 questions, one question moves MRR by about 0.05

EXPERIMENTS = [
    ("E1: ingestion (per_page chunks, dense search)", [
        ("raw text (PyMuPDF)", "e1_raw"),
        ("vision transcription", "e1_vision"),
    ]),
    ("E2: chunking (vision text, dense search)", [
        ("per_page", "e2_per_page"),
        ("fixed 500 / overlap 80", "e2_fixed"),
        ("heading", "e2_heading"),
    ]),
    ("E3: retrieval (per_page chunks, vision text)", [
        ("dense", "e3_dense"),
        ("BM25", "e3_bm25"),
        ("hybrid (RRF, k=60)", "e3_hybrid"),
    ]),
]


def load_result(name: str, root: Path = RESULTS_DIR) -> dict | None:
    path = root / f"{name}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def best_label(rows: list[tuple[str, dict]]) -> str | None:
    """Label of the row with the highest MRR; ties go to recall@3."""
    if not rows:
        return None
    return max(rows, key=lambda r: (r[1]["overall"]["mrr"], r[1]["overall"]["recall@3"]))[0]


def near_ties(rows: list[tuple[str, dict]], margin: float = NEAR_TIE) -> list[str]:
    """Labels, other than the best, whose MRR is within `margin` of the best MRR."""
    winner = best_label(rows)
    if winner is None:
        return []
    top = dict(rows)[winner]["overall"]["mrr"]
    return [label for label, res in rows
            if label != winner and top - res["overall"]["mrr"] <= margin]


def table(rows: list[tuple[str, dict | None]]) -> str:
    lines = [
        "| config | recall@1 | recall@3 | recall@5 | MRR | MRR math | MRR non-math |",
        "|---|---|---|---|---|---|---|",
    ]
    for label, res in rows:
        if res is None:
            lines.append(f"| {label} | not run | | | | | |")
            continue
        o = res["overall"]
        lines.append(
            f"| {label} | {o['recall@1']:.2f} | {o['recall@3']:.2f} | {o['recall@5']:.2f} "
            f"| {o['mrr']:.2f} | {res['math']['mrr']:.2f} | {res['not_math']['mrr']:.2f} |"
        )
    return "\n".join(lines)


def build_summary(root: Path = RESULTS_DIR) -> str:
    parts = ["# Results summary", "",
             "Generated by `python -m src.make_summary`. Do not edit by hand.", "",
             "n = answerable eval questions (math and non-math split shown by MRR). "
             "recall@k is not comparable across chunk sizes: a fixed chunk covers more pages "
             "than a per-page chunk, so the same k covers more pages. MRR and recall@1 are the "
             "fairer comparison across chunking strategies.", ""]
    best_overall = []
    for title, configs in EXPERIMENTS:
        rows = [(label, load_result(name, root)) for label, name in configs]
        done = [(label, res) for label, res in rows if res is not None]
        parts += [f"## {title}", "", table(rows), ""]
        winner = best_label(done)
        if winner:
            parts += [f"Best by the rule: **{winner}**", ""]
            ties = near_ties(done)
            if ties:
                parts += [f"Near tie (MRR within {NEAR_TIE} of the best, about one question): "
                          f"{', '.join(ties)}. Do not read this as a real difference.", ""]
            best_overall.append((title.split(":")[0], winner + (" (near tie)" if ties else "")))
    if best_overall:
        parts += ["## Best config so far", ""] + [f"- {exp}: {label}" for exp, label in best_overall] + [""]
    return "\n".join(parts)


def main() -> None:
    text = build_summary()
    (RESULTS_DIR / "summary.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
